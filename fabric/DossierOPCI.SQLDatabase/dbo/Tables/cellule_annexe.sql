CREATE TABLE [dbo].[cellule_annexe] (
    [entite]           VARCHAR (20)    NOT NULL,
    [arrete]           VARCHAR (20)    NOT NULL,
    [version]          INT             NOT NULL,
    [article]          VARCHAR (10)    NOT NULL,
    [ligne]            NVARCHAR (120)  NOT NULL,
    [colonne]          TINYINT         NOT NULL,
    [libelle]          NVARCHAR (500)  NOT NULL,
    [ordre]            SMALLINT        NOT NULL,
    [groupe]           VARCHAR (40)    NULL,
    [signe]            VARCHAR (4)     NULL,
    [valeur_numerique] DECIMAL (19, 6) NULL,
    [valeur_texte]     NVARCHAR (2000) NULL,
    [format]           VARCHAR (10)    NOT NULL,
    [etat]             VARCHAR (12)    NOT NULL,
    [texte_affiche]    NVARCHAR (2000) NOT NULL,
    [texte_imprime]    NVARCHAR (2000) NOT NULL,
    [obligation]       VARCHAR (14)    NULL,
    [nature]           VARCHAR (8)     NOT NULL,
    [comptee]          BIT             NOT NULL,
    [attend_exigee]    BIT             NOT NULL,
    [attend]           NVARCHAR (MAX)  NULL,
    [regle]            VARCHAR (12)    NOT NULL,
    [source]           NVARCHAR (MAX)  NOT NULL,
    [formule]          NVARCHAR (MAX)  NULL,
    [motif]            NVARCHAR (MAX)  NULL,
    [valeur_base]      NVARCHAR (2000) NULL,
    [saisie_ecartee]   NVARCHAR (400)  NULL,
    [calcul_id]        INT             NOT NULL,
    [calcule_le]       DATETIME2 (3)   NOT NULL,
    [calcule_par]      NVARCHAR (400)  NOT NULL,
    CONSTRAINT [pk_cellule_annexe] PRIMARY KEY CLUSTERED ([entite] ASC, [arrete] ASC, [version] ASC, [article] ASC, [ligne] ASC, [colonne] ASC),
    CONSTRAINT [ck_cellule_annexe_attend] CHECK ([attend_exigee]=(0) OR [etat]='EN_ATTENTE'),
    CONSTRAINT [ck_cellule_annexe_comptee] CHECK ([comptee]=case when [etat]='A_REMPLIR' then (1) else (0) end),
    CONSTRAINT [ck_cellule_annexe_etat] CHECK ([etat]='EN_ATTENTE' OR [etat]='SANS_OBJET' OR [etat]='A_REMPLIR' OR [etat]='SAISI' OR [etat]='CALCULE' OR [etat]='LU'),
    CONSTRAINT [ck_cellule_annexe_format] CHECK ([format]='texte' OR [format]='surface' OR [format]='unitaire' OR [format]='pct' OR [format]='nombre' OR [format]='montant'),
    CONSTRAINT [ck_cellule_annexe_nature] CHECK ([nature]='modele' OR [nature]='calcul' OR [nature]='etat' OR [nature]='source' OR [nature]='texte'),
    CONSTRAINT [ck_cellule_annexe_obligation] CHECK ([obligation]='FACULTATIVE' OR [obligation]='CONDITIONNELLE' OR [obligation]='IMPOSEE'),
    CONSTRAINT [fk_cellule_annexe_version] FOREIGN KEY ([entite], [arrete], [version]) REFERENCES [dbo].[annexe_version] ([entite], [arrete], [version])
);


GO

